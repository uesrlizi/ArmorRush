def P(pts, fill, sw=4, stroke='#181B20', extra=''):
    s = ' '.join(f'{x:.0f},{y:.0f}' for x, y in pts)
    st = f' stroke="{stroke}" stroke-width="{sw}"' if stroke else ''
    return f'<polygon points="{s}" fill="{fill}"{st}{extra}/>'

def R(x, y, w, h, fill, sw=0, stroke='', rx=0, extra=''):
    st = f' stroke="{stroke}" stroke-width="{sw}"' if stroke else ''
    r = f' rx="{rx}"' if rx else ''
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}"{st}{r}{extra}/>'

def C(cx, cy, r, fill, sw=0, stroke=''):
    st = f' stroke="{stroke}" stroke-width="{sw}"' if stroke else ''
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{fill}"{st}/>'

def LN(x1, y1, x2, y2, stroke, w):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{stroke}" stroke-width="{w}"/>'

