def fx_surge():
    """涌浪水体 3200x400（条带钉镜头，**浪冠在纹理顶缘 y=0**——节点把顶缘
    钉在当前水面高度，水体向下延伸 400）。半透青绿水体（alpha 烘在色里）
    +浪冠白沫排+体内浪纹+浮沫点。普通混合（不 ADD：水遮桥面要读出实体感）。"""
    import random as _r
    rng = _r.Random(7090)
    s = Svg(3200, 400)
    body = s.vgrad("surgeb", [(0, "#2e948a", 0.82), (0.4, "#227a74", 0.74),
                              (0.8, "#1b6460", 0.62), (1, "#175a58", 0.5)])
    # 浪冠团（先画团，顶缘=团的弧，白沫压在弧上）
    x = 0.0
    while x < 3220:
        rx = rng.uniform(50, 130)
        ry = rng.uniform(12, 26)
        s.ellipse(x + rx * 0.5, 8 + rng.uniform(-4, 8), rx, ry, TEAL_DEEP, 0.85)
        x += rx * rng.uniform(0.7, 1.2)
    s.rect(0, 8, 3200, 392, body)
    # 浪冠白沫
    x = 0.0
    while x < 3220:
        rx = rng.uniform(36, 100)
        s.ellipse(x + rx * 0.5, 6 + rng.uniform(-5, 6), rx, 6, FOAM, rng.uniform(0.5, 0.85))
        x += rx * rng.uniform(0.8, 1.4)
    for _ in range(90):
        s.circle(rng.uniform(10, 3190), rng.uniform(-2, 16), rng.uniform(1.0, 2.2), WHITE,
                 rng.uniform(0.4, 0.8))
    # 体内浪纹（暗/亮交替横纹，越深越稀）
    for by, op in ((60, 0.3), (140, 0.24), (240, 0.18), (330, 0.12)):
        for _ in range(20):
            wx = rng.uniform(40, 3120)
            ww = rng.uniform(80, 240)
            s.ellipse(wx, by + rng.uniform(-24, 24), ww, 5, "#0f4f4c", op)
            s.ellipse(wx + ww * 0.3, by + rng.uniform(-24, 24), ww * 0.5, 3.5, "#8fdcce", op * 0.8)
    return s


