    s.glow_ellipse(380, 306, 240, 26, "#f6b898", 0.28)
    for cy2, rx2, op in ((96, 200, 0.2), (140, 260, 0.16), (186, 180, 0.14)):  # 薄云横条
        s.ellipse(rng.uniform(260, 940), cy2, rx2, 9, "#f2d0ac", op)

    # ---- 远景：盐晶塔群（左平地两座全高；台缘后三座只露台顶以上）----
    far = "#8a6e5e"
    s.poly([(0, GROUND), (60, 296), (150, 288), (240, 300), (330, GROUND)], far, 0.65)
    for cx3, w3, h3 in ((96, 72, 110), (172, 52, 150),      # t0 平地：全高可见
                        (500, 46, 128), (620, 58, 158),     # t2 台缘后：露 ~202/172..268
                        (790, 48, 104)):                    # t1 台缘后：露 ~226..300
        s.poly([(cx3 - w3 / 2, GROUND), (cx3 - w3 * 0.2, GROUND - h3 * 0.7),
                (cx3, GROUND - h3), (cx3 + w3 * 0.25, GROUND - h3 * 0.6),
                (cx3 + w3 / 2, GROUND)], far, 0.8)
        s.line(cx3, GROUND - h3, cx3 + w3 * 0.1, GROUND - h3 * 0.5, "#f0e2c4", 1.6, 0.6)

    # ---- 远景地标：采盐联合机停上 t1 台面（v3 跨档把滚轮半截埋进台体，v4 整机
    #      停稳：着地件底缘全部 ≈299/300=t1 台顶 300）----
    # 坐标账：车体 (830..1000, 248..292)；驾驶楼 (884..932, 220..248)；滚轮
    # (862,278) r22 底 300；后轮对 (952/984,284) r15 底 299；履带座 (288..299)；
    # 输送臂从车体右后挑出台缘悬在 t0 上空
