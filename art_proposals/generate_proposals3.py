    # (953,289)；立环圆心 (1000,262) r54 覆盖 150°→60°（环底 316 段被台缘自然
    # 遮挡）；出轨 (1027,309)→(1200,232) 出画；支柱只立 t0 露档，顶端按轨道
    # 解析 y 落（不穿轨）
