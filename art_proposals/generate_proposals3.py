def bulb_string(s, x0, y0, x1, y1, sag, n, cols):
    """锚在实物上的灯串：Q 曲线本体 + 沿线灯泡（中点即控制点）。"""
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2 + sag
    s.path(f"M {f(x0)},{f(y0)} Q {f(cx)},{f(cy)} {f(x1)},{f(y1)}",
           stroke="#141a28", w=1.2, opacity=0.8)
    for i in range(1, n):
        t = i / n
        bx = (1 - t) ** 2 * x0 + 2 * (1 - t) * t * cx + t ** 2 * x1
        by = (1 - t) ** 2 * y0 + 2 * (1 - t) * t * cy + t ** 2 * y1
        glow_dot(s, bx, by, cols[i % len(cols)], r=1.5, halos=((4, 0.4), (7, 0.14)))


