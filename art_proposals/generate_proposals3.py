# 方案十 · 绿渊林场（阴天雾林：灰绿天光 + 巨木林带 + 放倒巨树年轮 + 伐木吊机）
# 坐标账：林地 y330；立木干径 16..30 干高 200..280（细高）；倒树横陈
# (784..1184, 干径 84=立木两倍粗，本章唯一大件)，切口年轮端面 (784,288)，
# 根部板根朝左；吊机 (1104..1196) 轮对坐树干上缘+双颚抓爪咬进干顶；
# 原木堆=前景深带 (918..1152, y336..380)；树桩木堆左 x96..280；中央留空。
# ============================================================
def forest_mill():
    rng = random.Random(1010)
    s = Svg()

    # 天空：阴天灰绿（色相锚，压中调——灰而不白，共享弹可读）。
    # 色带账 (0,#8a9a84)(0.6,#a8b49c)(1,#c2c4a8)
    sky = s.vgrad("sky10", [(0, "#8a9a84", 1), (0.6, "#a8b49c", 1), (1, "#c2c4a8", 1)])
    s.rect(0, 0, W, GROUND, sky)
    for cy3, rx3, ry3, op in ((70, 230, 13, 0.25), (120, 300, 16, 0.3),
                              (170, 200, 11, 0.2)):  # 层积云横团
        cxx = rng.uniform(280, 920)
        s.ellipse(cxx, cy3, rx3, ry3, "#9aa890", op)
        s.ellipse(cxx + rx3 * 0.2, cy3 + ry3 * 0.6, rx3 * 0.85, ry3 * 0.6,
                  "#7c8a74", op * 0.7)

    # ---- 远景：巨木林带剪影（三角冠坐干顶=悬空不可能，只排 x<720；右侧留给倒树地标）----
    far_t = "#3e523e"
    x = -20.0
    while x < 720:
        tw2 = rng.uniform(16, 30)
        th2 = rng.uniform(200, 280)
        top = GROUND - th2
        s.rect(x, top, tw2, th2, far_t, 0.62)
        cw = tw2 * rng.uniform(2.4, 3.4)           # 冠幅=干径 2.4~3.4 倍
        ch = rng.uniform(64, 100)                   # 冠高
        s.poly([(x + tw2 / 2 - cw / 2, top + 14), (x + tw2 / 2, top - ch),
                (x + tw2 / 2 + cw / 2, top + 14)], far_t, 0.62)      # 主冠三角
        s.poly([(x + tw2 / 2 - cw / 2 - 7, top + 44), (x + tw2 / 2, top - ch + 34),
                (x + tw2 / 2 + cw / 2 + 7, top + 44)], far_t, 0.55)  # 下层冠裙
        x += tw2 + rng.uniform(20, 64)
    haze_band(s, 210, GROUND, "#a8b49c", 0.3)

    # ---- 氛围雨丝（提前画：被中景/道具压住，不出现「游离细线」）----
    for _ in range(14):
        lx, ly = rng.uniform(40, W), rng.uniform(30, 240)
        ln = rng.uniform(12, 26)
        s.line(lx, ly, lx - ln * 0.25, ly + ln, "#d6e2cc", 1.4,
               rng.uniform(0.15, 0.28), cap="round")

    # ---- 中景：巨树桩×2（年轮朝上）----
    midf = "#37452e"
    s.rect(96, 286, 64, 44, midf, 0.95)                     # 树桩A
    s.ellipse(128, 286, 32, 10, "#5e704e", 0.95)
    s.ellipse(128, 286, 22, 7, midf, 0.95)
    s.ellipse(128, 286, 12, 4, "#5e704e", 0.95)
    s.rect(232, 296, 48, 34, midf, 0.95)                    # 树桩B
    s.ellipse(256, 296, 24, 8, "#5e704e", 0.95)
    s.ellipse(256, 296, 15, 5, midf, 0.95)

    # ---- 地表（拆地块 v2：林地泥台）----
    ground_v2.draw_ground(s, "p10_forest", bottom=H, k=1.0)

    # ---- 地标：放倒巨树 + 伐木吊机（右；v4 挪到 ground 之后画——v3 跨档被
    #      t1 台体盖掉下缘=可见干径中途 54→84px 台阶状断裂；现在横陈台地
    #      前沿全干可见）----
    # 坐标账：树干横陈 (784..1184, 干径 84=立木两倍粗)；根部板根朝左；
    # 切口端面年轮 (784,288) 三环；吊机车体 (1104..1196,186..230)、底车架+轮对
    # 坐树干上缘 246、折臂从车体左上拱出、双颚抓爪 (1064,228→252) 咬进干顶
    trunk = "#4e3c2e"
    s.rect(784, 246, 400, 84, trunk, 0.85)
    s.poly([(784, 330), (746, 314), (784, 254)], trunk, 0.85)
    s.ellipse(784, 288, 20, 42, "#9a7a54", 0.95)                    # 切口端面（年轮三环）
    s.ellipse(784, 288, 13, 28, "#7a5c3e", 0.95)
    s.ellipse(784, 288, 6.5, 14, "#9a7a54", 0.95)
    s.line(820, 262, 872, 262, "#3e2f22", 2, 0.6)                   # 树干裂纹
    s.line(900, 300, 960, 300, "#3e2f22", 2, 0.5)
    for bx3 in (900, 1010):                                         # 断枝残桩
        s.line(bx3, 246, bx3 + rng.choice((-14, 14)), 228, trunk, 6, 0.85)
    ldm = "#54604c"
    s.rect(1104, 186, 92, 44, ldm, 0.9)                     # 吊机车体
    s.rect(1124, 166, 28, 20, ldm, 0.9)                     # 驾驶楼
    s.rect(1112, 230, 76, 12, "#485440", 0.9)               # 底车架
    for wx4 in (1122, 1178):
        s.circle(wx4, 246, 7, "#3a4634", 0.95)              # 轮对坐在树干上缘
    s.line(1108, 190, 1080, 158, ldm, 5, 0.9)               # 折臂上段
    s.line(1080, 158, 1064, 228, ldm, 4, 0.9)               # 折臂下段
    s.line(1064, 228, 1054, 252, "#485440", 2.5, 0.95)      # 抓爪左颚
    s.line(1064, 228, 1074, 252, "#485440", 2.5, 0.95)      # 抓爪右颚
    s.line(1052, 252, 1076, 252, "#485440", 2, 0.95)        # 颚尖横梁（咬进干顶）
    glow_dot(s, 1144, 170, "#d87a30", r=1.8, halos=((4, 0.4), (8, 0.14)))  # 警示橙灯

    # ---- 地表/前景道具 ----
    # 锯末堆（土堆形，坐在走道带上不跨地面线；萤黄绿压到尘感）
    s.poly([(118, 330), (138, 316), (156, 312), (178, 318), (198, 330)], "#9aab3e", 0.5)
    s.poly([(206, 330), (222, 322), (238, 330)], "#aabb46", 0.38)
    # 前景原木堆（深带贴土墙，倒树下方独立成垛，不与树干叠）
    for ly5, lw4, lx4 in ((348, 224, 918), (362, 200, 932)):
        s.rect(lx4, ly5, lw4, 11, "#3a2e22", 0.95)
        s.line(lx4, ly5, lx4 + lw4, ly5, "#5e4a36", 1.6, 0.8)
    for lx5, ly6 in ((930, 353), (964, 368), (998, 353), (1104, 355), (1138, 369)):
        s.circle(lx5, ly6, 12, "#5e4a36", 0.95)
        s.circle(lx5, ly6, 7.5, "#8a6a48", 0.95)
        s.circle(lx5, ly6, 2.5, "#5e4a36", 0.95)
    # 蕨叶剪影两丛
    for fx3, fy3, sc in ((60, 330, 1.0), (1160, 332, 0.85)):
        for a2 in (-70, -40, -10, 20, 50):
            aa2 = math.radians(a2)
            s.line(fx3, fy3, fx3 + 44 * sc * math.cos(aa2),
                   fy3 - 44 * sc * math.sin(aa2), "#242e1c", 2.4 * sc, 0.9)

    # 氛围：锯末飞尘 + 低雾
    for _ in range(10):
        s.circle(rng.uniform(100, 1100), rng.uniform(200, 330), rng.uniform(1, 2),
                 "#c8e070", rng.uniform(0.2, 0.5))
    haze_band(s, 250, GROUND, "#b8c4ac", 0.25)
    return s


