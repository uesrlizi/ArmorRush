# 方案八 · 镜盐之原（黄昏盐湖：杏金绯粉天光 + 盐晶塔 + 搁浅采盐联合机 + 镜洼）
# 坐标账：盐原 y330；霞带 y280..330；联合机（本章唯一大件）整机停 t1 台面
# x824..1002，着地件底缘 ≈299/300 + 接地阴影，输送臂挑出台缘悬 t0 上空。
# **档位区账（道具落位先对这张表，v3 教训：v2 的洼/塔画进台体地界被立面吃掉）**：
#   t0=[-100,220]∪[1020,1500] 顶 330 / t2=[220,700] 顶 268 / t1=[700,1020] 顶 300。
#   远层塔群：左平地两座全高 + t2/t1 台缘后三座只露台顶以上段；
#   镜洼四洼全画在档顶以上：左平地 (176,318) / t2 带面 (470,276) /
#   t1 带面 (830,304) / 右平地 (1150,320)，**ground 之后画**。
# ============================================================
def salt_mirror():
    rng = random.Random(909)
    s = Svg()

    # 天空：黄昏（色相锚杏金→绯粉，压中调）。色带账 (0,#b8824e)(0.5,#dca878)(1,#f0b890)
    sky = s.vgrad("sky9", [(0, "#b8824e", 1), (0.5, "#dca878", 1), (1, "#f0b890", 1)])
    s.rect(0, 0, W, GROUND, sky)
    # 霞带（不画太阳盘——黄昏光交给渐变+霞带，同六章「太阳挤不进独层」教训）
    s.glow_ellipse(600, 316, 420, 44, "#f6c8a0", 0.4)
    s.glow_ellipse(380, 306, 240, 26, "#f6b898", 0.28)
    for cy2, rx2, op in ((96, 200, 0.2), (140, 260, 0.16), (186, 180, 0.14)):  # 薄云横条
        s.ellipse(rng.uniform(260, 940), cy2, rx2, 9, "#f2d0ac", op)

    # ---- 远景：盐晶塔群（左平地两座全高；台缘后三座只露台顶以上）----
    far = "#8a6e5e"
    s.poly([(0, GROUND), (60, 296), (150, 288), (240, 300), (330, GROUND)], far, 0.65)
    for cx3, w3, h3 in ((96, 72, 110), (172, 52, 150),      # t0 平地：全高可见
                        (500, 46, 128), (620, 58, 158),     # t2 台缘后：露 ~202/172..268
                        (790, 48, 104)):                    # t1 台缘后：露 ~226..300
        s.poly([(cx3 - w3 / 2, GROUND), (cx3 - w3 * 0.2, GROUND - h3 * 0.7),
                (cx3, GROUND - h3), (cx3 + w3 * 0.25, GROUND - h3 * 0.6),
                (cx3 + w3 / 2, GROUND)], far, 0.8)
        s.line(cx3, GROUND - h3, cx3 + w3 * 0.1, GROUND - h3 * 0.5, "#f0e2c4", 1.6, 0.6)

    # ---- 远景地标：采盐联合机停上 t1 台面（v3 跨档把滚轮半截埋进台体，v4 整机
    #      停稳：着地件底缘全部 ≈299/300=t1 台顶 300）----
    # 坐标账：车体 (830..1000, 248..292)；驾驶楼 (884..932, 220..248)；滚轮
    # (862,278) r22 底 300；后轮对 (952/984,284) r15 底 299；履带座 (288..299)；
    # 输送臂从车体右后挑出台缘悬在 t0 上空
    s.ellipse(912, 299, 95, 4, "#4a3628", 0.55)            # 接地阴影（先画）
    mec = "#6a4a3c"
    s.rect(824, 288, 178, 11, "#5a4234", 0.9)              # 履带座暗带
    s.rect(830, 248, 170, 44, mec, 0.9)                    # 车体
    s.rect(884, 220, 48, 28, mec, 0.9)                     # 驾驶楼
    s.circle(862, 278, 22, mec, 0.9)                       # 巨型滚轮
    s.circle(862, 278, 11, "#5a3c30", 0.9)
    for tx2 in (952, 984):                                  # 后轮对
        s.circle(tx2, 284, 15, mec, 0.9)
    s.line(975, 252, 1120, 142, mec, 6, 0.9)               # 输送臂
    s.line(975, 262, 1116, 154, mec, 3, 0.9)
    s.rect(1096, 132, 26, 16, mec, 0.9)                    # 臂端卸料斗
    glow_dot(s, 908, 218, "#f2789f", r=2.0, halos=((5, 0.4), (9, 0.15)))  # 信号粉灯

    # ---- 中景：泵站小屋（左平地缩小让位镜洼）+ 出盐管桥（短腿坐 t2 台缘）----
    mid = "#8a7460"
    s.rect(40, 266, 96, 64, mid, 0.95)
    s.poly([(36, 266), (140, 266), (88, 248)], "#7a6552", 0.95)    # 檐顶
    s.rect(68, 296, 20, 34, "#5f4e3e", 0.95)                       # 门
    s.rect(108, 280, 14, 12, "#f0d0a8", 0.75)                      # 亮窗
    for py2 in (250, 258):                                         # 出盐管两道
        s.line(136, py2, 380, py2, "#7a6552", 4, 0.95)
    s.line(180, 258, 180, GROUND, "#6a5846", 2.5, 0.95)            # t0 落地腿
    for px3 in (300, 348):                                         # t2 台面短腿
        s.line(px3, 258, px3, 268, "#6a5846", 3, 0.95)
    s.line(380, 250, 380, 268, "#7a6552", 4, 0.95)                 # 立管弯头落台面
    s.rect(366, 252, 20, 16, "#6a5846", 0.95)                      # 泵座坐在台缘
    s.line(196, GROUND, 196, 254, "#6a5846", 2, 0.95)              # 测盐旗杆（左平地，插镜洼）
    s.poly([(196, 256), (224, 262), (196, 270)], "#f2789f", 0.9)   # 信号粉旗

    # ---- 地表（拆地块 v2：盐壳台地）----
    ground_v2.draw_ground(s, "p8_salt", bottom=H, k=1.0)

    # ---- 镜洼四洼（ground 之后画：洼面全在档顶以上/平地段，不进台体地界）----
    for mx3, mw3, my3, ry3 in ((176, 96, 318, 5.5), (470, 110, 276, 4.5),
                               (830, 110, 304, 4.0), (1150, 130, 320, 5.0)):
        s.ellipse(mx3, my3, mw3 / 2, ry3, "#4aa89a", 0.85)
        s.ellipse(mx3, my3 - ry3 * 0.3, mw3 / 2 - 10, ry3 * 0.5,
                  "#f6b898", 0.6)                                  # 映霞
        s.line(mx3 - mw3 / 2 + 8, my3 + ry3 * 0.4,
               mx3 + mw3 / 2 - 6, my3 + ry3 * 0.4, "#ffd8b0", 1.3, 0.6)
        s.line(mx3 - mw3 / 2 + 14, my3 - ry3 * 0.4,
               mx3 + mw3 / 2 - 18, my3 - ry3 * 0.4, "#8ad0c0", 1.0, 0.5)

    # ---- 地表剪影道具（盐堆坐在 t2/t1 带面，界桩右平地站在洼里）----
    s.poly([(310, 268), (330, 254), (352, 268)], "#e8dcc0", 0.95)   # 盐堆（t2 带面）
    s.poly([(786, 300), (804, 288), (824, 300)], "#e8dcc0", 0.9)    # 盐堆（t1 带面）
    s.line(1146, 330, 1172, 300, "#6a5846", 2.5, 0.9)               # 倒伏界桩（右平地）
    s.poly([(1172, 300), (1188, 306), (1172, 312)], "#f2789f", 0.85)

    # 氛围：蜃气横掠 + 盐尘
    for _ in range(10):
        lx, ly = rng.uniform(60, W), rng.uniform(120, 300)
        ln = rng.uniform(40, 100)
        s.line(lx, ly, lx - ln, ly + ln * 0.04, "#f2d8b4", 1.6,
               rng.uniform(0.14, 0.3), cap="round")
    for _ in range(12):
        s.circle(rng.uniform(0, W), rng.uniform(150, 320), rng.uniform(1, 2),
                 "#f8e8cc", rng.uniform(0.15, 0.4))
    return s


